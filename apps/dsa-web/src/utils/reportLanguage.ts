import type { ReportLanguage } from '../types/analysis';

export const normalizeReportLanguage = (value?: string | null): ReportLanguage => {
  const normalized = (value || '').trim().toLowerCase().replace(/_/g, '-');
  if (normalized === 'en') {
    return 'en';
  }
  if (normalized === 'zh-tw') {
    return 'zh-TW';
  }
  if (normalized === 'ko') {
    return 'ko';
  }
  return 'zh';
};

