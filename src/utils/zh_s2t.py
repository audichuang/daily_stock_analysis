_CHAR_TABLE = {
    ord(_CHAR_PAIRS[index]): _CHAR_PAIRS[index + 1]
    for index in range(0, len(_CHAR_PAIRS) - 1, 2)
    if _CHAR_PAIRS[index] != _CHAR_PAIRS[index + 1]
}

_PHRASE_RE = re.compile(
    "|".join(re.escape(key) for key in sorted(_PHRASES, key=len, reverse=True))
)


def to_traditional(text: str) -> str:
    """把模板文字轉成繁體（台灣用語）；已是繁體的部分不變。"""
    if not text:
        return text
    converted = _PHRASE_RE.sub(lambda match: _PHRASES[match.group(0)], text)
    return converted.translate(_CHAR_TABLE)


def localize_template(text: str, language: str) -> str:
    """語言是 zh-TW 才轉換；zh、en、ko 原樣回傳。"""
    return to_traditional(text) if language == "zh-TW" else text
